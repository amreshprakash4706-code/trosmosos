export const APP_BY_ID: Record<string, AppDef> = Object.fromEntries(
  APP_CATALOG.map((a) => [a.id, a]),
);

export function searchApps(q: string): AppDef[] {
  const s = q.trim().toLowerCase();
  if (!s) return APP_CATALOG;
  return APP_CATALOG.filter(
    (a) =>
      a.name.toLowerCase().includes(s) ||
      a.description.toLowerCase().includes(s) ||
      a.category.toLowerCase().includes(s) ||
      a.id.includes(s) ||
      a.keywords.some((k) => k.includes(s)),
  );
}

export const DEFAULT_DOCK = APP_CATALOG.filter((a) => a.dock).map((a) => a.id);
